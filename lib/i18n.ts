export const formatTranslation = (
  template: string,
  replacements: Record<string, string>,
) => {
  let value = template;

  Object.entries(replacements).forEach(([key, replacement]) => {
    value = value.replace(new RegExp(`\\{${key}\\}`, "g"), replacement);
  });

  return value;
};
